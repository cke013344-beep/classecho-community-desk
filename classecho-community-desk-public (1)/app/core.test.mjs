import assert from 'node:assert/strict';
import {generate,seed,parseBackup,validRecord,review,csv} from './core.mjs';
const rows=Object.fromEntries(seed().map(r=>[r.id,r]));
rows.discussion={id:'discussion',type:'knowledge',data:{title:'尚未批准福利',category:'活动规则',body:'领取100天免费会员',status:'讨论方案'}};
const p=generate(rows,'2026-11-01',60);
assert.equal(p.candidates.length,3);
for(const budget of [15,30,60,90,240])assert.equal(generate(rows,'2026-11-01',budget).tasks.reduce((a,x)=>a+x.minutes,0),budget);
assert.equal(p.tasks.length,3);assert.equal(p.tasks.reduce((a,x)=>a+x.minutes,0),60);
assert(!JSON.stringify(p).includes('100天'));
assert(p.candidates.every(c=>c.status==='草稿'&&c.body.length>=60&&c.body.length<=150));
rows.published={id:'published',type:'content',data:{...p.candidates[0],status:'已发布'}};
assert.notEqual(generate(rows,'2026-11-01',60).candidates[0].title,p.candidates[0].title);
const backup=JSON.stringify({version:1,records:Object.values(rows)});
assert.deepEqual(parseBackup(backup).records,Object.values(rows));
assert.throws(()=>parseBackup('{"version":1,"records":[{"id":"x"}]}'));
assert(!validRecord({id:'__proto__',type:'task',data:{title:'bad'}}));
assert(!validRecord({id:'x',type:'task',data:{title:{bad:1}}}));
assert(review(rows,'2026-11-01','2026-11-07').includes('耗时 未知'));
rows.result={id:'result',type:'result',data:{title:'确认使用',date:'2026-11-01',outcome:'有人完成真实使用',source:'成员私下确认',member:'M01',minutes:'12',notes:'完成首次使用'}};
const summary=review(rows,'2026-11-01','2026-11-07');
assert(summary.includes('有人完成真实使用（成员私下确认）'));assert(summary.includes('12 分钟'));
assert(csv([{id:'1',data:{title:'=SUM(A1)'}}]).includes("'=SUM"));
console.log('PASS: 生成三候选/时间预算/未确认权益隔离/文案长度/发布去重/备份恢复/格式校验/实际记录复盘/CSV公式保护');
